"""Compare Prisma STT configurations on acted probe clips; writes bench/probe/probe_report.md.

    python scripts/probe_prisma_formats.py --clips 8 [--yes]

Clips: bench/corpus/probe/<clip_id>.(wav|m4a|mp3|ogg|webm); truth from bench/manifest.jsonl (clip_id match).
"""

import argparse
import asyncio
import json
import sys
from dataclasses import asdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app import audio  # noqa: E402
from app.gnani import stt  # noqa: E402
from app.gnani.http import GnaniError  # noqa: E402
from app.nlp import numbers as N  # noqa: E402
from app.nlp.extractor import find_bank  # noqa: E402

CONFIGS = {
    "A_v25_verbatim": stt.SttProfile(model="v2.5", language="ta-IN", format="verbatim"),
    "B_v25_transcribe": stt.SttProfile(model="v2.5", language="ta-IN", format="transcribe"),
    "C_v3_transcribe": stt.SttProfile(model="v3.0", language="ta-IN,en-IN", format="transcribe",
                                      topic="Cyber fraud complaint: bank, UPI, amount, phone number, transaction ID",
                                      keyterms=["UTR", "UPI", "OTP", "SBI", "HDFC", "PhonePe", "GPay"]),
    "D_v3_codemix": stt.SttProfile(model="v3.0", language="ta-IN,en-IN", format="codemix"),
    "E_v3_transliterate": stt.SttProfile(model="v3.0", language="indic-auto", format="transliterate"),
}
ROOT = Path("bench")
EXTS = (".wav", ".m4a", ".mp3", ".ogg", ".webm", ".flac")


def load_truth() -> dict[str, dict]:  # type: ignore[type-arg]
    m = ROOT / "manifest.jsonl"
    out = {}
    if m.exists():
        for line in m.read_text(encoding="utf-8").splitlines():
            if line.strip():
                row = json.loads(line)
                out[row["clip_id"]] = row.get("field_truth", {})
    return out


def score(text: str, truth: dict) -> dict:  # type: ignore[type-arg]
    """Strict exact match, using the same parsers the app uses (no lenient substring matching)."""
    res = {}
    if "amount" in truth:
        res["amount"] = N.parse_amount(text).value == truth["amount"]
    spans = N.find_number_spans(text)
    for f, n in (("suspect_phone", 10), ("utr", 12)):
        if f in truth:
            res[f] = any(sp.digits == truth[f] for sp in spans) or N.parse_digit_string(text, n).value == truth[f]
    if "bank" in truth:
        b = find_bank(text)
        res["bank"] = bool(b) and b[0] == truth["bank"]
    return res


async def main(n_clips: int, yes: bool) -> int:
    clips = sorted(p for p in (ROOT / "corpus" / "probe").iterdir() if p.suffix in EXTS)[:n_clips]         if (ROOT / "corpus" / "probe").exists() else []
    if not clips:
        print("No clips in bench/corpus/probe/")
        return 2
    total = len(clips) * len(CONFIGS)
    print(f"{len(clips)} clips × {len(CONFIGS)} configs = {total} STT calls (cached results are free).")
    if total > 50:
        print("More than 50 calls — needs explicit approval.")
    if not yes and input("Proceed? [y/N] ").strip().lower() != "y":
        return 1
    truth = load_truth()
    out_dir = ROOT / "probe"
    out_dir.mkdir(exist_ok=True)
    rows: dict[str, list[dict]] = {k: [] for k in CONFIGS}  # type: ignore[type-arg]
    for clip in clips:
        wav = await audio.normalize(clip.read_bytes())
        for name, prof in CONFIGS.items():
            try:
                r = await stt.transcribe(wav, profile=prof, request_id=f"probe-{clip.stem}-{name}")
                rec = {"clip_id": clip.stem, **asdict(r)}
            except GnaniError as e:
                rec = {"clip_id": clip.stem, "error": f"{e.status} {e.code} {e.message}"}
            rows[name].append(rec)
            print(f"  {clip.stem} {name}: {'ERR ' + rec['error'] if 'error' in rec else 'ok'}")
    for name, recs in rows.items():
        (out_dir / f"{name}.jsonl").write_text(
            "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in recs), encoding="utf-8")

    fields = ["amount", "suspect_phone", "utr", "bank"]
    lines = ["# Prisma probe report", "",
             f"Clips: {len(clips)} ({', '.join(c.stem for c in clips)}). Generated by scripts/probe_prisma_formats.py.",
             "Scoring is strict exact match using the app's own parsers (numbers.py, extractor.find_bank).", "",
             "| config · channel | amount | phone | UTR | bank | errors | median latency | number methods |",
             "|---|---|---|---|---|---|---|---|"]
    failures: list[str] = []
    examples: dict[str, list[str]] = {}
    for name, recs in rows.items():
        channels = ["text"] + (["literal"] if any(r.get("literal") for r in recs) else [])
        for ch in channels:
            agg: dict[str, list[bool]] = {f: [] for f in fields}
            methods: dict[str, int] = {}
            errs = sum(1 for r in recs if "error" in r)
            lat = sorted(r["latency_ms"] for r in recs if "error" not in r and not r.get("cached"))
            for rec in recs:
                if "error" in rec:
                    continue
                txt = rec.get(ch) or ""
                t = truth.get(rec["clip_id"], {})
                for k, v in score(txt, t).items():
                    agg[k].append(v)
                    if not v:
                        failures.append(f"| {name} · {ch} | {rec['clip_id']} | {k} | {t.get(k)} | {txt[:150]} |")
                for sp in N.find_number_spans(txt):
                    methods[sp.method] = methods.get(sp.method, 0) + 1
                if ch == "text":
                    examples.setdefault(name, [])
                    if len(examples[name]) < 3:
                        examples[name].append(
                            f"- `{rec['clip_id']}`: {rec['text'][:220]}"
                            + (f"  \n  literal: {rec['literal'][:220]}" if rec.get("literal") else ""))

            def fmt(v: list[bool]) -> str:
                return f"{sum(v)}/{len(v)}" if v else "n/a"

            med = f"{lat[len(lat) // 2]} ms" if lat else "cached"
            lines.append(f"| {name} · {ch} | " + " | ".join(fmt(agg[f]) for f in fields)
                         + f" | {errs} | {med} | {', '.join(f'{k}:{v}' for k, v in sorted(methods.items()))} |")
    lines += ["", "## Failures (field not exactly recovered)", "",
              "| config · channel | clip | field | truth | transcript (first 150 chars) |", "|---|---|---|---|---|",
              *failures, "", "## Raw examples (synthetic clips, fake numbers)", ""]
    for name, ex in examples.items():
        lines += [f"### {name}", *ex, ""]
    lines += ["## Decision", "", "_See docs/API_NOTES.md._"]
    (out_dir / "probe_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out_dir / 'probe_report.md'}")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--clips", type=int, default=8)
    ap.add_argument("--yes", action="store_true", help="skip confirmation prompt")
    a = ap.parse_args()
    sys.exit(asyncio.run(main(a.clips, a.yes)))
