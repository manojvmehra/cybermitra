"""bench/results/run.jsonl -> bench/RESULTS.md (n + Wilson 95% CI). Never hand-edit RESULTS.md."""

import json
import math
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def cell(k: int, n: int) -> str:
    if n == 0:
        return "—"
    lo, hi = wilson(k, n)
    return f"{k}/{n} = {100 * k / n:.0f}% [{100 * lo:.0f}–{100 * hi:.0f}]"


def pct(xs: list[int], p: float) -> int | None:
    if not xs:
        return None
    s = sorted(xs)
    return s[min(len(s) - 1, int(round(p * (len(s) - 1))))]


START, END = "<!-- RESULTS:START (generated by bench/report.py, do not edit) -->", "<!-- RESULTS:END -->"


def embed_in_readme(results: str) -> None:
    """README embeds RESULTS.md verbatim between markers, so the README never carries hand-typed numbers."""
    readme = ROOT.parent / "README.md"
    s = readme.read_text(encoding="utf-8")
    if START not in s or END not in s:
        return
    head, rest = s.split(START, 1)
    _, tail = rest.split(END, 1)
    body = results.replace("# Benchmark results", "### Benchmark results (generated)", 1)
    readme.write_text(f"{head}{START}\n{body}{END}{tail}", encoding="utf-8")
    print("Embedded RESULTS.md into README.md")


def simulation_section() -> list[str]:
    """Call-level SIMULATION from bench/results/sim.jsonl (bench/simulate_calls.py). Labelled as such."""
    path = ROOT / "results" / "sim.jsonl"
    if not path.exists():
        return []
    sims = [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]
    if not sims:
        return []
    n = len(sims)
    contained = sum(s["status"] == "ready_for_review" for s in sims)
    reasons: dict[str, int] = defaultdict(int)
    for s in sims:
        if s["handoff_reason"]:
            reasons[s["handoff_reason"]] += 1
    want = [s for s in sims if s["expected_handoff"]]
    got = [s for s in sims if s["status"] == "needs_human"]
    tp = sum(1 for s in got if s["expected_handoff"])
    wrong = sum(len(s["wrong_confirmed"]) for s in sims)
    fields = sorted({f for s in sims for f in list(s["corrections"]) + list(s["typed"]) + s["unconfirmed"]})
    secs = sorted(s["sim_seconds"]["clips"] + s["sim_seconds"]["stt"] + s["sim_seconds"]["tts_estimated"]
                  for s in sims)
    med = secs[len(secs) // 2] if secs else None
    L = ["", "## Call SIMULATION (real FSM over the saved transcripts; oracle caller)", "",
         "`bench/simulate_calls.py` replays each clip's real Prisma transcript as the caller's story, then an "
         "oracle answers every read-back against ground truth and types what the story did not give. "
         "No API calls. **This is a simulation, not a user study.** The oracle never asks for a person and "
         "always knows the answer, so containment here only shows the dialogue does not dead-end.", "",
         f"- Simulated calls: {n} ({sum(s['synthetic_tts'] for s in sims)} from TTS clips)",
         f"- Containment (ended `ready_for_review`, no human): {cell(contained, n)}",
         f"- Handoffs by reason: {dict(reasons) or 'none'}",
         f"- Intended handoffs caught (recall): {cell(tp, len(want)) if want else '— (no handoff scripts in this run)'}"
         f"; handoffs that were intended (precision): {cell(tp, len(got)) if got else '— (no handoffs)'}",
         f"- **Wrong digits that reached the packet as confirmed: {wrong}** (0 by design: every digit is "
         "confirmed chunk by chunk or typed)",
         f"- Simulated handling time, median: {med:.0f} s = caller clips + STT latency + prompt speech "
         f"estimated at {13} chars/s; excludes the caller's thinking and typing time" if med is not None else "",
         "", "| field | read-back corrections | typed (voice gave no valid value) | left unconfirmed |",
         "|---|---|---|---|"]
    for f in fields:
        L.append(f"| {f} | {sum(s['corrections'].get(f, 0) for s in sims)} | "
                 f"{sum(s['typed'].get(f, 0) for s in sims)} | {sum(s['unconfirmed'].count(f) for s in sims)} |")
    return L


def main() -> int:
    path = ROOT / "results" / "run.jsonl"
    if not path.exists():
        print("Run bench/run_benchmark.py first.")
        return 2
    rows = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    ok_rows = [r for r in rows if "error" not in r]
    conds = sorted({r["condition"] for r in ok_rows})
    fields = sorted({f for r in ok_rows for f in r.get("fields", {})})

    by: dict[tuple[str, str], list[bool]] = defaultdict(list)
    methods: dict[tuple[str, str], list[bool]] = defaultdict(list)
    agree_acc: dict[str, list[bool]] = defaultdict(list)
    readback: dict[str, list[dict]] = defaultdict(list)  # type: ignore[type-arg]
    for r in ok_rows:
        for f, v in r["fields"].items():
            by[(f, r["condition"])].append(bool(v["exact"]))
            by[(f, "ALL")].append(bool(v["exact"]))
            methods[(f, v.get("method") or "none")].append(bool(v["exact"]))
            if "readback_sim" in v:
                readback[f].append(v["readback_sim"])
        for f, a in (r.get("agreement") or {}).items():
            agree_acc[f"{f}|agree" if a["agree"] else f"{f}|disagree"].append(bool(a["itn_exact"] or
                                                                                  a["literal_exact"]))
            agree_acc[f"{f}|rate"].append(bool(a["agree"]))

    model = ok_rows[0]["stt_model"] if ok_rows else "?"
    fmt = ok_rows[0]["stt_format"] if ok_rows else "?"
    clips = len({r["clip_id"] for r in ok_rows})
    speakers = len({r.get("speaker") for r in ok_rows})
    synthetic = len({r["clip_id"] for r in ok_rows if r.get("synthetic_tts")})
    L = ["# Benchmark results", "",
         f"Generated by `bench/report.py` from `bench/results/run.jsonl`. Prisma {model}, format `{fmt}`.",
         f"{clips} clips ({synthetic} **TTS-generated**, {clips - synthetic} acted by people), {speakers} voices, "
         f"{len(rows)} clip×condition runs ({len(rows) - len(ok_rows)} API errors). "
         "Cells: k/n = % [Wilson 95% CI].", "",
         *(["> **These clips are machine speech (Timbre TTS): clean, unemotional, read from a script. They show "
            "how the pipeline behaves, not how it does on real victims. Replace with acted human clips.**", ""]
           if synthetic else []),
         "## Field exact-match before read-back", "",
         "| field | " + " | ".join(conds) + " | all |", "|---|" + "---|" * (len(conds) + 1)]
    for f in fields:
        L.append(f"| {f} | " + " | ".join(cell(sum(by[(f, c)]), len(by[(f, c)])) for c in conds)
                 + f" | {cell(sum(by[(f, 'ALL')]), len(by[(f, 'ALL')]))} |")

    L += ["", "## Dual-channel agreement (ITN transcript vs `output.literal`)", "",
          "| field | agreement rate | accuracy when agree | accuracy when disagree (either channel) |",
          "|---|---|---|---|"]
    for f in sorted({k.split("|")[0] for k in agree_acc}):
        a, d, rt = agree_acc[f"{f}|agree"], agree_acc[f"{f}|disagree"], agree_acc[f"{f}|rate"]
        L.append(f"| {f} | {cell(sum(rt), len(rt))} | {cell(sum(a), len(a))} | {cell(sum(d), len(d))} |")

    L += ["", "## Number format breakdown (extractor `method`)", "", "| field | method | exact |", "|---|---|---|"]
    for (f, m), v in sorted(methods.items()):
        L.append(f"| {f} | {m} | {cell(sum(v), len(v))} |")

    L += ["", "## Read-back SIMULATION (oracle user, not real users)", "",
          "An oracle answers yes/no per chunk against ground truth. This measures *how much correcting the "
          "user would have to do*, not accuracy.", "",
          "| field | n | missing (needs full re-ask) | mean chunk corrections (when present) | would end unconfirmed |",
          "|---|---|---|---|---|"]
    for f, sims in sorted(readback.items()):
        present = [s for s in sims if not s["missing"]]
        mean = sum(s["corrections"] for s in present) / len(present) if present else 0
        L.append(f"| {f} | {len(sims)} | {sum(s['missing'] for s in sims)} | {mean:.2f} | "
                 f"{sum(bool(s['unconfirmed']) for s in present)} |")

    L += simulation_section()

    lat = [r["latency_ms"] for r in ok_rows if not r.get("cached") and r.get("latency_ms")]
    live = len(lat)
    L += ["", "## Cost and latency", "",
          f"- Live STT calls in this run: {live} (cached: {len(ok_rows) - live})",
          f"- STT latency p50 / p95 (live calls): {pct(lat, 0.5)} ms / {pct(lat, 0.95)} ms",
          "", "## Limitations", "",
          ("- TTS-generated clips (clean machine speech, no emotion, no real background noise); small n — read "
           "the confidence intervals." if synthetic == clips else
           "- Acted clips by consenting team members with fake numbers; small n — read the confidence intervals."),
          "- 'missing' means the number came out the wrong length and was rejected by validation, so the app "
          "asks again; it is not a silent wrong value.",
          "- Telephone band is simulated (band-pass + 8 kHz µ-law), not a real phone line.",
          "- Read-back numbers are a simulation with a perfect user."]
    text = "\n".join(L) + "\n"
    (ROOT / "RESULTS.md").write_text(text, encoding="utf-8")
    print(f"Wrote {ROOT / 'RESULTS.md'}")
    embed_in_readme(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
